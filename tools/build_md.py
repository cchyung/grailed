#!/usr/bin/env python3
"""Regenerate listings.md from listings.json. listings.json is the only file to edit by hand.

  .venv/bin/python tools/build_md.py
"""
import json
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def money(v):
    return f"${v:,}" if isinstance(v, (int, float)) else "?"


def price_cell(it):
    s = money(it["price"])
    hist = it.get("price_history") or []
    if hist:
        s += f" (was {money(hist[0]['from'])})"
    return s


def main():
    data = json.loads((ROOT / "listings.json").read_text())
    items = data["items"]
    L = ["# Grailed Listings", "",
         "Generated from listings.json by tools/build_md.py. Do not edit this file by hand.", "",
         "Photos: `photos/out/<folder>/01.jpg` onward, 01 is the cover. Measurements in inches, laid flat.", ""]

    batches = OrderedDict()
    for it in items:
        batches.setdefault(it.get("listed_at") or "Not listed yet", []).append(it)

    for batch, group in batches.items():
        L += ["---", "", f"## Batch {batch}", "",
              "| Item | Price | Floor | Status | Link |", "|---|---|---|---|---|"]
        for it in group:
            link = f"https://www.grailed.com/listings/{it['grailed_id']}" if it.get("grailed_id") else ""
            L.append(f"| {it['name']} | {price_cell(it)} | {money(it.get('floor'))} | {it.get('status') or 'unchecked'} | {link} |")
        L.append("")
        for it in group:
            cond = it["condition"] + (f" ({it['condition_score']}/10)" if it.get("condition_score") else "")
            size = it["size"] + (f" (tagged {it['tag_size']})" if it.get("tag_size") else "")
            L += [f"### {it['name']}",
                  f"**Folder:** {it['folder']} · **Price:** {money(it['price'])} · **Size:** {size} · **Condition:** {cond}  ",
                  f"**Category:** {it['category']} > {it['subcategory']} · **Color:** {it['color']} · **Style:** {it['style']}"
                  + (f" · **Country:** {it['country']}" if it.get("country") else ""),
                  "", it["description"], ""]
    (ROOT / "listings.md").write_text("\n".join(L))
    print(f"listings.md rebuilt ({len(items)} items)")


if __name__ == "__main__":
    main()
